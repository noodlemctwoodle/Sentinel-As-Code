#>

[CmdletBinding(SupportsShouldProcess)]
param(
    [Parameter(Mandatory = $true)]
    [string]$SiteUrl,

    [Parameter(Mandatory = $false)]
    [string]$Title = 'iSOC Blueprint',

    [Parameter(Mandatory = $true)]
    [string]$Owner,

    [Parameter(Mandatory = $true)]
    [string]$PublisherAppId,

    [Parameter(Mandatory = $false)]
    [string]$PublisherAppName = 'Sentinel Documenter SharePoint publisher',

    [Parameter(Mandatory = $true)]
    [string]$ClientId,

    [Parameter(Mandatory = $true)]
    [string]$Tenant,

    [Parameter(Mandatory = $false)]
    [string]$TenantAdminUrl,

    [Parameter(Mandatory = $false)]
    [string]$AppPackagePath
)

$ErrorActionPreference = 'Stop'

. (Join-Path $PSScriptRoot 'Private/SacSharePoint.ps1')

$SiteUrl = $SiteUrl.TrimEnd('/')
if (-not $TenantAdminUrl) {
    if ($SiteUrl -notmatch '^https://(?<t>[^./]+)\.sharepoint\.com/') { throw "Cannot derive the admin URL from '$SiteUrl'; pass -TenantAdminUrl." }
    $TenantAdminUrl = "https://$($Matches['t'])-admin.sharepoint.com"
}
if ($AppPackagePath -and -not (Test-Path -LiteralPath $AppPackagePath)) { throw "App package not found: $AppPackagePath" }

Write-Host 'iSOC Blueprint site bootstrap' -ForegroundColor Cyan
Write-Host "  Site      : $SiteUrl"
Write-Host "  Admin     : $TenantAdminUrl"
Write-Host "  Publisher : $PublisherAppName ($PublisherAppId)"

Connect-PnPOnline -Url $TenantAdminUrl -ClientId $ClientId -Tenant $Tenant -Interactive

# 1. Site --------------------------------------------------------------------
$existing = Get-PnPTenantSite -Identity $SiteUrl -ErrorAction SilentlyContinue
if ($existing) {
    Write-Host '  Site exists.'
}
elseif ($PSCmdlet.ShouldProcess($SiteUrl, 'Create communication site')) {
    New-PnPSite -Type CommunicationSite -Title $Title -Url $SiteUrl -Owner $Owner -SiteDesign Blank -Wait | Out-Null
    Write-Host '  Site created.'
}

# 2. App catalogs ------------------------------------------------------------
$tenantCatalog = Get-PnPTenantAppCatalogUrl
if (-not $tenantCatalog) {
    throw 'This tenant has no app catalog. Create one first (Register-PnPAppCatalogSite, or the SharePoint admin centre), then re-run.'
}
$siteCatalog = Get-PnPSiteCollectionAppCatalog -ErrorAction SilentlyContinue |
    Where-Object { ([string]$_.AbsoluteUrl).TrimEnd('/') -eq $SiteUrl }
if ($siteCatalog) {
    Write-Host '  Site collection app catalog exists.'
}
elseif ($PSCmdlet.ShouldProcess($SiteUrl, 'Add site collection app catalog')) {
    Add-PnPSiteCollectionAppCatalog -Site $SiteUrl
    Write-Host '  Site collection app catalog added.'
}

# 3. Publisher access (Sites.Selected, this site only) -----------------------
$grant = Get-PnPEntraIDAppSitePermission -Site $SiteUrl -ErrorAction SilentlyContinue |
    Where-Object { @($_.Apps | ForEach-Object { [string]$_.Id }) -contains $PublisherAppId } |
    Select-Object -First 1
if ($grant -and (@($grant.Roles) -contains 'fullcontrol')) {
    Write-Host '  Publisher already has FullControl on the site.'
}
elseif ($grant) {
    if ($PSCmdlet.ShouldProcess($SiteUrl, "Raise $PublisherAppName to FullControl")) {
        Set-PnPEntraIDAppSitePermission -Site $SiteUrl -PermissionId $grant.Id -Permissions FullControl | Out-Null
        Write-Host '  Publisher raised to FullControl.'
    }
}
elseif ($PSCmdlet.ShouldProcess($SiteUrl, "Grant $PublisherAppName FullControl")) {
    Grant-PnPEntraIDAppSitePermission -AppId $PublisherAppId -DisplayName $PublisherAppName -Site $SiteUrl -Permissions FullControl | Out-Null
    Write-Host '  Publisher granted FullControl.'
}

# 4. Site settings -----------------------------------------------------------
if ($PSCmdlet.ShouldProcess($SiteUrl, 'Disable page comments and enable the mega menu')) {
    Connect-PnPOnline -Url $SiteUrl -ClientId $ClientId -Tenant $Tenant -Interactive
    Set-PnPSite -CommentsOnSitePagesDisabled:$true
    Set-PnPWeb -MegaMenuEnabled:$true
    Write-Host '  Page comments off, mega menu on.'
}

# 5. Optional first app deploy ------------------------------------------------
if ($AppPackagePath) {
    if (-not $WhatIfPreference) { Connect-PnPOnline -Url $SiteUrl -ClientId $ClientId -Tenant $Tenant -Interactive }
    Publish-SacAppPackage -Path $AppPackagePath | Out-Null
}

Write-Host "`nNext steps:" -ForegroundColor Green
Write-Host '  - Add the people who should read the site to its Visitors group, and no one else.'
Write-Host "  - Set the pipeline's site URL to $SiteUrl (see Docs/Pipelines/SharePoint-Publish.md)."
Write-Host '  - Run the SharePoint publish pipeline, or Publish-SentinelDocsSite.ps1 -Interactive -WhatIf to preview.'
