#Requires -Version 7.4
#Requires -Modules @{ ModuleName = 'PnP.PowerShell'; ModuleVersion = '3.4.1' }

<#
.SYNOPSIS
    One-time bootstrap of an iSOC Blueprint SharePoint site for one
    Sentinel workspace. Run interactively by a SharePoint administrator.

.DESCRIPTION
    Everything inside the site is generated by Publish-SentinelDocsSite.ps1
    on every pipeline run. This script does the part a pipeline should not
    have the rights to do, once:

      1. Creates the communication site (blank design) if it does not
         exist yet.
      2. Checks the tenant app catalog exists (site collection app
         catalogs depend on it) and adds a site collection app catalog to
         this site, so the dashboard web part is deployed to this site
         only and the pipeline never needs tenant-wide app rights.
      3. Grants the publisher app registration FullControl on this site
         only (Sites.Selected). FullControl is the level the site
         collection app catalog, home page and navigation changes need.
      4. Turns off page comments and turns on the mega menu, which suits
         the generated family navigation.
      5. Optionally deploys the dashboard web part package, so the first
         pipeline run does not wait for it to appear.

    It is safe to re-run: each step checks before it changes anything.

    Prerequisites:
      - The publisher app registration has the SharePoint (not Microsoft
        Graph) application permission Sites.Selected, with admin consent,
        and a federated credential for each pipeline.
      - The app you sign in with (-ClientId) has delegated
        Sites.FullControl.All (to grant site access) and you are a
        SharePoint administrator.

    Site membership is the privacy boundary: the site shows tenant
    configuration, findings and role assignments. Keep the Visitors and
    Members groups to the people who should read it.

.PARAMETER SiteUrl
    URL of the site to create or prepare, for example
    https://contoso.sharepoint.com/sites/isoc-law-sentinel-prod.

.PARAMETER Title
    Site title used when creating the site. Defaults to 'iSOC Blueprint'.

.PARAMETER Owner
    UPN of the site owner, used when creating the site.

.PARAMETER PublisherAppId
    Client (application) id of the publisher app registration the
    pipelines use.

.PARAMETER PublisherAppName
    Display name recorded with the site permission grant.

.PARAMETER ClientId
    Your Entra app registration for interactive PnP sign-in.

.PARAMETER Tenant
    Tenant, for example contoso.onmicrosoft.com.

.PARAMETER TenantAdminUrl
    SharePoint admin centre URL. Defaults to https://<tenant>-admin.sharepoint.com
    derived from -SiteUrl.

.PARAMETER AppPackagePath
    Optional path to sentinel-navigator.sppkg to deploy now.

.EXAMPLE
    ./Tools/Documenter/SharePoint/Initialize-SentinelDocsSite.ps1 `
        -SiteUrl 'https://contoso.sharepoint.com/sites/isoc-law-sentinel-prod' `
        -Owner 'secops-lead@contoso.com' `
        -PublisherAppId '<publisher-app-id>' `
        -ClientId '<your-pnp-app-id>' -Tenant 'contoso.onmicrosoft.com' -WhatIf

    Shows what the bootstrap would do. Drop -WhatIf to run it.

.NOTES
