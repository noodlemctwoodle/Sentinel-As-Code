# Keeps the file help above from being read as the help of the function below.

function ConvertTo-iSOCDcrArmTemplate {
    <#
    .SYNOPSIS
        Build the ARM template of a data collection rule for one table.

    .DESCRIPTION
        One Microsoft.Insights/dataCollectionRules resource at the
        DataCollectionRules api-version (2023-03-11, the first with
        endpoints, so a Direct rule gets its own logs ingestion endpoint):
        the stream declaration, the logFiles data source when given, the
        workspace destination and one data flow through the transform. The
        description and the data collection endpoint are set only when
        given. Every key is in a fixed order, so the same table always
        writes the same file.

    .PARAMETER Name
        The rule's name.

    .PARAMETER Region
        Its location, the workspace's.

    .PARAMETER Kind
        Direct, Windows or Linux.

    .PARAMETER Stream
        The input stream's name, Custom-<table>.

    .PARAMETER StreamColumn
        The stream's columns.

    .PARAMETER WorkspaceResourceId
        The destination workspace.

    .PARAMETER OutputStream
        The destination stream, Custom-<table>.

    .PARAMETER Transform
        The transform.

    .PARAMETER EndpointResourceId
        A data collection endpoint.

    .PARAMETER LogFilesDataSource
        The text log data source, for a Windows or Linux rule.

    .PARAMETER Description
        The rule's description.

    .OUTPUTS
        [System.Collections.Specialized.OrderedDictionary] The template.

    .EXAMPLE
        ConvertTo-iSOCDcrArmTemplate -Name dcr-myapp -Region uksouth -Kind Direct -Stream Custom-MyApp_CL -StreamColumn $columns -WorkspaceResourceId $ctx.WorkspaceResourceId -OutputStream Custom-MyApp_CL -Transform source
    #>
    [CmdletBinding()]
    [OutputType([System.Collections.Specialized.OrderedDictionary])]
    param(
        [Parameter(Mandatory)]
        [string] $Name,

        [Parameter(Mandatory)]
        [string] $Region,

        [Parameter(Mandatory)]
        [string] $Kind,

        [Parameter(Mandatory)]
        [string] $Stream,

        [Parameter(Mandatory)]
        [object[]] $StreamColumn,

        [Parameter(Mandatory)]
        [string] $WorkspaceResourceId,

        [Parameter(Mandatory)]
        [string] $OutputStream,

        [Parameter(Mandatory)]
        [string] $Transform,

        [string] $EndpointResourceId,

        [object] $LogFilesDataSource,

        [string] $Description
    )

    $properties = [ordered]@{}
    if ($Description) { $properties['description'] = $Description }
    if ($EndpointResourceId) { $properties['dataCollectionEndpointId'] = $EndpointResourceId }
    $properties['streamDeclarations'] = [ordered]@{
        $Stream = [ordered]@{ columns = @($StreamColumn) }
    }
    if ($LogFilesDataSource) { $properties['dataSources'] = [ordered]@{ logFiles = @($LogFilesDataSource) } }
    $properties['destinations'] = [ordered]@{
        logAnalytics = @(
            [ordered]@{
                workspaceResourceId = $WorkspaceResourceId
                name                = 'workspaceDestination'
            }
        )
    }
    $properties['dataFlows'] = @(
        [ordered]@{
            streams      = @($Stream)
            destinations = @('workspaceDestination')
            transformKql = $Transform
            outputStream = $OutputStream
        }
    )

    [ordered]@{
        '$schema'      = 'https://schema.management.azure.com/schemas/2019-04-01/deploymentTemplate.json#'
        contentVersion = '1.0.0.0'
        metadata       = [ordered]@{
            description = "Data collection rule for $OutputStream, generated by Invoke-iSOCClassicTableMigration."
        }
        resources      = @(
            [ordered]@{
                type       = 'Microsoft.Insights/dataCollectionRules'
                apiVersion = Get-iSOCApiVersion DataCollectionRules
                name       = $Name
                location   = $Region
                kind       = $Kind
                properties = $properties
            }
        )
    }
}
