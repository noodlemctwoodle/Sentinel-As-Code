# Keeps the file help above from being read as the help of the function below.

function ConvertTo-iSOCTableArmTemplate {
    <#
    .SYNOPSIS
        Build the ARM template that creates or updates the custom table.

    .DESCRIPTION
        One Microsoft.OperationalInsights/workspaces/tables resource at the
        TablePlans api-version (2025-07-01; earlier versions know no
        Auxiliary plan). Each column carries only what the Tables API
        defines: name and type, then its dataTypeHint (only with
        -IncludeDataTypeHint: the live service refuses the documented
        values), description and display name when it has them. The
        description and plan are set when given. retentionInDays is sent
        only for an Analytics table (or no plan), since it is read-only on
        Basic and Auxiliary, where giving it is a warning; 0 means not
        given, -1 the workspace default. Every key is in a fixed order, so
        the same schema always writes the same file.

    .PARAMETER WorkspaceName
        The workspace's name.

    .PARAMETER Table
        The table name.

    .PARAMETER Column
        The accepted columns.

    .PARAMETER Plan
        Analytics, Basic or Auxiliary.

    .PARAMETER Retention
        Interactive retention in days; 0 for not given.

    .PARAMETER TotalRetention
        Total retention in days; 0 for not given.

    .PARAMETER TableDescription
        The table's description.

    .PARAMETER IncludeDataTypeHint
        Send each column's dataTypeHint.

    .OUTPUTS
        [System.Collections.Specialized.OrderedDictionary] The template.

    .EXAMPLE
        ConvertTo-iSOCTableArmTemplate -WorkspaceName law-sentinel -Table MyApp_CL -Column $columns -Plan Analytics
    #>
    [CmdletBinding()]
    [OutputType([System.Collections.Specialized.OrderedDictionary])]
    param(
        [Parameter(Mandatory)]
        [string] $WorkspaceName,

        [Parameter(Mandatory)]
        [string] $Table,

        [Parameter(Mandatory)]
        [object[]] $Column,

        [string] $Plan,

        [int] $Retention,

        [int] $TotalRetention,

        [string] $TableDescription,

        [switch] $IncludeDataTypeHint
    )

    $schema = [ordered]@{
        name    = $Table
        columns = @($Column | ForEach-Object {
                $entry = [ordered]@{ name = $_.Name; type = $_.Type }
                if ($IncludeDataTypeHint -and $_.DataTypeHint) { $entry['dataTypeHint'] = $_.DataTypeHint }
                if ($_.Description) { $entry['description'] = $_.Description }
                if ($_.DisplayName) { $entry['displayName'] = $_.DisplayName }
                $entry
            })
    }
    if ($TableDescription) { $schema['description'] = $TableDescription }

    $properties = [ordered]@{ schema = $schema }
    if ($Plan) { $properties['plan'] = $Plan }

    if ($Retention -ne 0) {
        if ($Plan -and $Plan -ne 'Analytics') {
            Write-iSOCLog "Ignoring -RetentionInDays: retentionInDays is read-only on a $Plan table." -Level Warning
        } else {
            $properties['retentionInDays'] = $Retention
        }
    }
    if ($TotalRetention -ne 0) { $properties['totalRetentionInDays'] = $TotalRetention }

    [ordered]@{
        '$schema'      = 'https://schema.management.azure.com/schemas/2019-04-01/deploymentTemplate.json#'
        contentVersion = '1.0.0.0'
        metadata       = [ordered]@{
            description = "Custom log table $Table, generated by New-iSOCDcrFromSchema."
        }
        resources      = @(
            [ordered]@{
                type       = 'Microsoft.OperationalInsights/workspaces/tables'
                apiVersion = Get-iSOCApiVersion TablePlans
                name       = "$WorkspaceName/$Table"
                properties = $properties
            }
        )
    }
}
