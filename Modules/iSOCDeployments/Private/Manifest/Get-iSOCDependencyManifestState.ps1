# Keeps the file help above from being read as the help of the function below.

function Get-iSOCDependencyManifestState {
    <#
    .SYNOPSIS
        Return what discovery found, what the manifest file holds and how
        they differ, logging the inventory and any missing watchlists.

    .DESCRIPTION
        The JSON is what Update-iSOCDependencyManifest would write. Its
        description still names Tools/Build-DependencyManifest.ps1, so the
        script and the module write the same file while both are in use;
        it changes at cut-over (MIGRATION.md edit E10).

    .PARAMETER RepoPath
        The repository root.

    .PARAMETER ManifestPath
        The manifest file. Defaults to dependencies.json at the root.

    .OUTPUTS
        [pscustomobject] RepoPath, ManifestPath (full), Exists, Entries,
        MissingWatchlists, HasDrift, Diff and Json.

    .EXAMPLE
        $state = Get-iSOCDependencyManifestState -RepoPath $repo
    #>
    [CmdletBinding()]
    [OutputType([pscustomobject])]
    param(
        [Parameter(Mandatory)]
        [string] $RepoPath,

        [string] $ManifestPath
    )

    if (-not $ManifestPath) { $ManifestPath = Join-Path $RepoPath 'dependencies.json' }
    $ManifestPath = [System.IO.Path]::GetFullPath($ManifestPath, (Get-Location).ProviderPath)

    $inventory = Get-iSOCDependencyInventory -RepoPath $RepoPath
    Write-iSOCLog 'Inventoried in-repo artifacts:'
    Write-iSOCLog "  Functions  (Parsers/):    $($inventory.Functions.Count)"
    Write-iSOCLog "  Watchlists (Watchlists/): $($inventory.Watchlists.Count)"

    $manifest = New-iSOCDependencyManifest -RepoPath $RepoPath -Inventory $inventory
    Write-iSOCLog ''
    Write-iSOCLog "Discovered $($manifest.Entries.Count) content items with declared dependencies."

    if ($manifest.MissingWatchlists.Count -gt 0) {
        Write-iSOCLog 'Watchlist references that do not resolve to in-repo Watchlists/:' -Level Warning
        foreach ($alias in $manifest.MissingWatchlists.Keys) {
            Write-iSOCLog "  - $alias, used by: $($manifest.MissingWatchlists[$alias] -join ', ')" -Level Warning
        }
        Write-iSOCLog '  Action: provision these watchlists out-of-band, or add them under Watchlists/.' -Level Warning
    }

    $exists = Test-Path -LiteralPath $ManifestPath -PathType Leaf
    $onDisk = @{}
    if ($exists) {
        $json = Get-Content -LiteralPath $ManifestPath -Raw | ConvertFrom-Json -Depth 32 -AsHashtable
        if ($json -and $json.dependencies) { $onDisk = $json.dependencies }
    }
    $comparison = Compare-iSOCDependencyManifest -Discovered $manifest.Entries -OnDisk $onDisk

    [pscustomobject]@{
        RepoPath          = $RepoPath
        ManifestPath      = $ManifestPath
        Exists            = $exists
        Entries           = $manifest.Entries
        MissingWatchlists = $manifest.MissingWatchlists
        HasDrift          = (-not $exists) -or $comparison.HasDrift
        Diff              = @($comparison.Diff)
        Json              = ConvertTo-iSOCManifestJson -Entries $manifest.Entries -Version '1.0' -Description 'Auto-generated by Tools/Build-DependencyManifest.ps1. Do not hand-edit; re-run the script after editing rules.'
    }
}
