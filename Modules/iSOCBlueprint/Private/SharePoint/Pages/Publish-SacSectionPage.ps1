# Keeps the file help above from being read as the help of the function below.

function Publish-SacSectionPage {
    <#
    .SYNOPSIS
        Create or rebuild one generated section page and publish it.

    .DESCRIPTION
        The page canvas is cleared and rebuilt through the PnP Core page
        object, so the whole page is saved and published once rather than
        once per web part. Rebuilding in place (rather than deleting and
        recreating) keeps the page URL and its version history, and a
        failed publish leaves the last published version live.

    .PARAMETER PageDoc
        One page document from the bundle's pages/ folder.

    .PARAMETER Create
        Create the page first (it does not exist yet).

    .PARAMETER WebServerRelativeUrl
        The web's server-relative URL, for links and image paths.

    .PARAMETER ChartComponentAvailable
        The chart web part is in the site's component list. Without it each
        chart is written as a Text web part holding its data as a table.

    .OUTPUTS
        [bool] $true when every chart was placed as the chart web part, so
        the caller can leave a page with stand-in tables to be rebuilt.
    #>
    [CmdletBinding(SupportsShouldProcess)]
    [OutputType([bool])]
    param(
        [Parameter(Mandatory)] $PageDoc,
        [switch] $Create,
        [Parameter(Mandatory)] [string] $WebServerRelativeUrl,
        [switch] $ChartComponentAvailable
    )

    $name = [string]$PageDoc.name
    if (-not $PSCmdlet.ShouldProcess("SitePages/$name.aspx", $(if ($Create) { 'Create and publish page' } else { 'Rebuild and publish page' }))) { return $true }

    $page = if ($Create) {
        Add-PnPPage -Name $name -LayoutType Article -Title ([string]$PageDoc.title)
    }
    else {
        Get-PnPPage -Identity $name
    }

    $page.PageTitle = [string]$PageDoc.title
    $page.ClearPage()
    $page.AddSection('OneColumn', 1, $null)
    $column = $page.Sections[0].Columns[0]

    $optionsType = $page.GetType().Assembly.GetType('PnP.Core.Model.SharePoint.PageImageOptions')
    $order = 1
    $allNative = $true
    $component = $null
    $looked = $false
    foreach ($seg in @($PageDoc.segments)) {
        if ($seg.type -eq 'chart') {
            if ($ChartComponentAvailable -and -not $looked) {
                # Once per page, by id ignoring braces and case (the same
                # lookup the dashboard page needs).
                $component = @($page.AvailablePageComponents($null)) |
                    Where-Object { ([string]$_.Id).Trim('{}').ToLowerInvariant() -eq $script:SacChartWebPartComponentId } |
                    Select-Object -First 1
                $looked = $true
            }
            if ($component) {
                $control = $page.NewWebPart($component)
                # Node links in a flowchart carry '~site/' like the page HTML.
                $chartJson = Resolve-SacSiteUrl -Text ($seg.chart | ConvertTo-Json -Depth 32 -Compress) -WebServerRelativeUrl $WebServerRelativeUrl
                $control.PropertiesJson = (@{ chartJson = $chartJson } | ConvertTo-Json -Compress)
            }
            else {
                $control = $page.NewTextPart((ConvertTo-SacChartFallbackHtml -Chart $seg.chart))
                $allNative = $false
            }
        }
        elseif ($seg.type -eq 'image') {
            $options = $null
            if ($optionsType) {
                $options = [Activator]::CreateInstance($optionsType)
                $options.AlternativeText = [string]$seg.alt
            }
            $url = "$($WebServerRelativeUrl.TrimEnd('/'))/$script:SacAssetsLibraryUrl/diagrams/$($seg.file)"
            $control = $page.GetImageWebPart($url, $options)
        }
        else {
            $control = $page.NewTextPart((Resolve-SacSiteUrl -Text ([string]$seg.html) -WebServerRelativeUrl $WebServerRelativeUrl))
        }
        $page.AddControl($control, $column, $order, $null)
        $order++
    }

    [void]$page.Save($name)
    $page.Publish('Generated by the iSOC Blueprint')
    return $allNative
}
